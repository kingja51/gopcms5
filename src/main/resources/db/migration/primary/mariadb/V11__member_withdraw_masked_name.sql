-- ============================================================================
-- V11 — 탈퇴 원장에 마스킹된 회원 이름 보관
--
-- 왜 필요한가:
--   원장(tb_member_withdraw)은 지금까지 해시(login_id_hash·di_hash)만 들고 있었다.
--   대조는 되지만 <b>사람이 목록을 읽을 수 없다</b> — 관리자 화면의 탈퇴 목록에서
--   어느 행이 누구인지 가늠할 단서가 하나도 없어, 문의 응대나 분쟁 확인 때 매번
--   해시를 다시 계산해야 했다.
--
-- 왜 평문이 아니라 마스킹인가:
--   원장의 성격은 "법정 최소항목만" 이다. 평문 이름을 넣으면 PII 파기(nullifyPii)를
--   해 놓고 같은 정보를 옆 표에 남기는 셈이 되어 파기의 의미가 사라진다.
--   마스킹 값(홍*동)은 되돌릴 수 없고 원본을 복구하는 경로도 없다 — 담당자가
--   "같은 사람인지" 대조할 만큼만 남긴다.
--   그래서 이 컬럼은 <b>암호화하지 않는다</b>(PiiTypeHandler 대상이 아니다).
--
-- 값은 누가 넣는가:
--   앱이 넣는다. tb_member.member_name 은 암호문({AG}…)이라 SQL 안에서 마스킹할 수
--   없다 — 서비스가 복호화된 이름을 Mask.name() 에 통과시킨 뒤 파라미터로 전달한다
--   (MemberLifecycleServiceImpl.withdraw).
--
-- 길이 150:
--   마스킹 결과는 원본과 같은 글자 수(홍길동 → 홍*동)라 tb_member.member_name 과
--   같은 여유를 둔다. 짧게 잡아 절단이 생기면 대조가 어긋난다.
--
-- 소급:
--   기존 행은 NULL 로 남는다. 원본이 이미 파기돼 채울 값이 없다 — 화면은 NULL 을
--   '-' 로 표시한다.
-- ============================================================================

ALTER TABLE `tb_member_withdraw`
    ADD COLUMN `member_name` varchar(150) DEFAULT NULL COMMENT '회원 이름 (마스킹)'
    AFTER `site_code`;
